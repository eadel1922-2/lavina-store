-- ملاحظة: عطّلي التسجيل العام من Authentication > Settings > Allow new users to sign up.
-- أنشئي حساب المدير يدويًا من Authentication > Users > Add user.

create table if not exists public.products (
  id bigint generated by default as identity primary key,
  name text not null,
  category text not null default 'أخرى',
  price numeric(10,2) not null check (price >= 0),
  sale_price numeric(10,2) null check (sale_price is null or sale_price >= 0),
  sizes text[] not null default '{}',
  colors text[] not null default '{}',
  description text not null default '',
  image_url text not null default '',
  active boolean not null default true,
  created_at timestamptz not null default now(),
  updated_at timestamptz not null default now(),
  constraint sale_price_not_above_price check (sale_price is null or sale_price <= price)
);

-- V.002: حقول التقييم (تُضاف بأمان حتى لو كان الجدول موجودًا من V.001)
alter table public.products
  add column if not exists rating numeric(2,1) not null default 0 check (rating >= 0 and rating <= 5),
  add column if not exists rating_count integer not null default 0 check (rating_count >= 0);

alter table public.products enable row level security;

drop policy if exists "Public can read active products" on public.products;
create policy "Public can read active products"
on public.products for select
to anon, authenticated
using (active = true);

drop policy if exists "Authenticated admins can read all products" on public.products;
create policy "Authenticated admins can read all products"
on public.products for select
to authenticated
using (true);

drop policy if exists "Authenticated admins can insert products" on public.products;
create policy "Authenticated admins can insert products"
on public.products for insert
to authenticated
with check (true);

drop policy if exists "Authenticated admins can update products" on public.products;
create policy "Authenticated admins can update products"
on public.products for update
to authenticated
using (true)
with check (true);

drop policy if exists "Authenticated admins can delete products" on public.products;
create policy "Authenticated admins can delete products"
on public.products for delete
to authenticated
using (true);

-- مساحة صور المنتجات: عامة للعرض، والرفع والحذف للمستخدمين المسجلين فقط.
insert into storage.buckets (id, name, public, file_size_limit, allowed_mime_types)
values ('product-images', 'product-images', true, 5242880, array['image/jpeg','image/png','image/webp'])
on conflict (id) do update set public = true, file_size_limit = 5242880,
allowed_mime_types = array['image/jpeg','image/png','image/webp'];

drop policy if exists "Public can view product images" on storage.objects;
create policy "Public can view product images"
on storage.objects for select
to anon, authenticated
using (bucket_id = 'product-images');

drop policy if exists "Authenticated users can upload product images" on storage.objects;
create policy "Authenticated users can upload product images"
on storage.objects for insert
to authenticated
with check (bucket_id = 'product-images');

drop policy if exists "Authenticated users can update product images" on storage.objects;
create policy "Authenticated users can update product images"
on storage.objects for update
to authenticated
using (bucket_id = 'product-images')
with check (bucket_id = 'product-images');

drop policy if exists "Authenticated users can delete product images" on storage.objects;
create policy "Authenticated users can delete product images"
on storage.objects for delete
to authenticated
using (bucket_id = 'product-images');

